export type Language = "zh-CN" | "en-US";
let activeLanguage: Language = "zh-CN";
if (typeof window !== "undefined") {
  const saved = window.localStorage.getItem("stagecraft_language");
  if (saved === "zh-CN" || saved === "en-US") activeLanguage = saved;
}

export function getLanguage(): Language {
  return activeLanguage;
}

export function setLanguage(language: Language): void {
  activeLanguage = language;
  if (typeof window !== "undefined") {
    window.localStorage.setItem("stagecraft_language", language);
  }
}

export const chrome: typeof zh = new Proxy(zh, {
  get(target, property, receiver) {
    if (typeof property !== "string" || !(property in target)) {
      return Reflect.get(target, property, receiver);
    }
    return activeLanguage === "en-US"
      ? (en[property as ChromeKey] ?? target[property as ChromeKey])
      : target[property as ChromeKey];
  },
});

const scientificStatusCopy: Record<
  string,
  { title: ChromeKey; note: ChromeKey }
> = {
  NOT_REPORTED: {
    title: "scientificStatusNotReported",
    note: "scientificStatusNotReportedNote",
  },
  FROZEN_PASS: {
    title: "scientificStatusFrozenPass",
    note: "scientificStatusFrozenPassNote",
  },
  FITTED: {
    title: "scientificStatusFitted",
    note: "scientificStatusFittedNote",
  },
  NOT_ESTIMABLE: {
    title: "scientificStatusNotEstimable",
    note: "scientificStatusNotEstimableNote",
  },
  INVALIDATED: {
    title: "scientificStatusInvalidated",
    note: "scientificStatusInvalidatedNote",
  },
};

export function scientificStatusTitle(status: string): string {
  const copy = scientificStatusCopy[status];
  return copy ? chrome[copy.title] : chrome.scientificStatusUnknown;
}

export function scientificStatusNote(status: string): string {
  const copy = scientificStatusCopy[status];
  return copy ? chrome[copy.note] : chrome.scientificStatusUnknownNote;
}

export function scientificLimitText(line: string): string {
  if (line.includes("校准状态保持为")) return "";
  if (line.includes("留一数据集不是独立复制")) return chrome.limitHoldout;
  if (line.includes("Part 4 的旗不是拟合结果")) return chrome.limitPart4;
  if (line.includes("NOT_ESTIMABLE 不表示效应不存在"))
    return chrome.limitNotEstimable;
  return line;
}

export function rowCount(total: number): string {
  return activeLanguage === "en-US" ? `${total} rows` : `共 ${total} 行`;
}
